import { describe, expect, it } from 'vitest';
import { categoryId, createCouple, registerUser, runJobs, setupApp } from './helpers';

const ctx = setupApp();

// Schedules use dates in 2099 so the scheduler's real "today" never interferes.
describe('scheduled incomes', () => {
  it('registers pay days automatically into the account, once', async () => {
    const me = await registerUser(ctx, 'Emmanuel');
    const account = await me.ok('POST', '/accounts', { name: 'Nómina', type: 'bank', currency: 'DOP', openingBalance: '1000' });
    const afp = (await me.ok<any[]>('GET', '/deduction-types')).find((t) => t.name === 'AFP');
    const source = await me.ok('POST', '/income-sources', {
      name: 'DGII',
      type: 'formal_employment',
      defaultCurrency: 'DOP',
      payFrequency: 'semimonthly',
      payDay: 15,
      secondPayDay: 31,
      scheduleStartDate: '2099-01-01',
      expectedGross: '50000',
      accountId: account.id,
      autoRegister: true,
      deductionTemplates: [{ deductionTypeId: afp.id, defaultAmount: '1435' }],
    });
    // The same deduction type can be repeated in the template (e.g. two insurances).
    const health = (await me.ok<any[]>('GET', '/deduction-types')).find((t) => t.name === 'Seguro complementario');
    const repeated = await me.put(`/income-sources/${source.id}`, {
      name: 'DGII',
      type: 'formal_employment',
      defaultCurrency: 'DOP',
      payFrequency: 'semimonthly',
      payDay: 15,
      secondPayDay: 31,
      scheduleStartDate: '2099-01-01',
      expectedGross: '50000',
      accountId: account.id,
      autoRegister: true,
      deductionTemplates: [
        { deductionTypeId: afp.id, defaultAmount: '1435' },
        { deductionTypeId: health.id, defaultAmount: '529.40' },
        { deductionTypeId: health.id, defaultAmount: '2529.28' },
      ],
    });
    expect(repeated.status).toBe(200);
    const [saved] = (await me.ok<any[]>('GET', '/income-sources')).filter((s) => s.id === source.id);
    expect(saved.deductionTemplates.map((t: any) => t.defaultAmount)).toEqual(['1435.00', '529.40', '2529.28']);
    // Back to the single AFP deduction for the rest of the test.
    await me.ok('PUT', `/income-sources/${source.id}`, {
      name: 'DGII',
      type: 'formal_employment',
      defaultCurrency: 'DOP',
      payFrequency: 'semimonthly',
      payDay: 15,
      secondPayDay: 31,
      scheduleStartDate: '2099-01-01',
      expectedGross: '50000',
      accountId: account.id,
      autoRegister: true,
      deductionTemplates: [{ deductionTypeId: afp.id, defaultAmount: '1435' }],
    });

    expect(await runJobs(ctx, me.me.household.id, '2099-01-31')).toEqual({ incomes: 2, expenses: 0 });
    expect(await runJobs(ctx, me.me.household.id, '2099-01-31')).toEqual({ incomes: 0, expenses: 0 });

    const entries = await me.ok<any[]>('GET', '/income-entries?month=2099-01');
    expect(entries.map((e) => e.payDate).sort()).toEqual(['2099-01-15', '2099-01-31']);
    expect(entries[0]).toMatchObject({ grossAmount: '50000.00', netAmount: '48565.00', autoGenerated: true, isEstimated: true, accountId: account.id });
    expect(entries[0].deductions).toHaveLength(1);

    const [acc] = await me.ok<any[]>('GET', '/accounts');
    expect(acc.balance).toBe('98130.00');

    // Adjusting the real amounts confirms the entry.
    const edited = await me.ok('PUT', `/income-entries/${entries[0].id}`, {
      sourceId: source.id,
      kind: 'salary',
      payDate: entries[0].payDate,
      grossAmount: '52000',
      currency: 'DOP',
      accountId: account.id,
      deductions: [{ deductionTypeId: afp.id, amount: '1492.40' }],
    });
    expect(edited).toMatchObject({ netAmount: '50507.60', isEstimated: false });

    // A deleted automatic payment is not recreated.
    await me.ok('DELETE', `/income-entries/${entries[1].id}`);
    expect(await runJobs(ctx, me.me.household.id, '2099-02-01')).toEqual({ incomes: 0, expenses: 0 });
  });

  it('validates what automatic registration needs and projects upcoming payments', async () => {
    const me = await registerUser(ctx, 'Juan');
    const bad = await me.post('/income-sources', {
      name: 'Sin cuenta',
      type: 'formal_employment',
      defaultCurrency: 'DOP',
      payDay: 30,
      scheduleStartDate: '2099-01-01',
      expectedGross: '1000',
      autoRegister: true,
    });
    expect(bad.status).toBe(400);

    await me.ok('POST', '/income-sources', {
      name: 'Freelance',
      type: 'freelance',
      defaultCurrency: 'USD',
      payFrequency: 'monthly',
      payDay: 1,
      scheduleStartDate: '2020-01-01',
      expectedGross: '1200',
    });
    const [source] = await me.ok<any[]>('GET', '/income-sources');
    expect(source.nextPayDate).toMatch(/^\d{4}-\d{2}-01$/);
    const upcoming = await me.ok<any[]>('GET', '/income-sources/upcoming?days=40');
    expect(upcoming.length).toBeGreaterThanOrEqual(1);
    expect(upcoming[0]).toMatchObject({ sourceName: 'Freelance', expectedNet: '1200.00', autoRegister: false });
  });
});

describe('automatic fixed expenses', () => {
  it('pays fixed expenses on their due date, estimates variable ones and keeps manual ones pending', async () => {
    const { owner, wife } = await createCouple(ctx);
    const housing = await categoryId(owner, 'Vivienda');
    const hid = owner.me.household.id;
    await owner.ok('POST', '/recurring-expenses', {
      name: 'Alquiler',
      categoryId: housing,
      amount: '35000',
      currency: 'DOP',
      scope: 'shared',
      dueDay: 5,
      startDate: '2099-01-01',
    });
    await owner.ok('POST', '/recurring-expenses', {
      name: 'Luz',
      amount: '3000',
      currency: 'DOP',
      scope: 'shared',
      dueDay: 20,
      isVariableAmount: true,
      paidByUserId: wife.me.id,
      startDate: '2099-01-01',
    });
    await owner.ok('POST', '/recurring-expenses', {
      name: 'Colegio',
      amount: '12000',
      currency: 'DOP',
      scope: 'personal',
      dueDay: 10,
      autoPay: false,
      startDate: '2099-01-01',
    });

    expect(await runJobs(ctx, hid, '2099-01-15')).toEqual({ incomes: 0, expenses: 2 });
    expect(await runJobs(ctx, hid, '2099-01-31')).toEqual({ incomes: 0, expenses: 1 });
    expect(await runJobs(ctx, hid, '2099-01-31')).toEqual({ incomes: 0, expenses: 0 });

    const jan = await owner.ok<any[]>('GET', '/expenses?month=2099-01');
    const byName = Object.fromEntries(jan.map((e) => [e.description, e]));
    expect(byName.Alquiler).toMatchObject({ status: 'paid', nature: 'fixed', autoGenerated: true, isEstimated: false, paidByUserId: owner.me.id });
    expect(byName.Alquiler.splits).toHaveLength(2);
    expect(byName.Luz).toMatchObject({ status: 'paid', isEstimated: true, paidByUserId: wife.me.id });
    expect(byName.Colegio).toMatchObject({ status: 'pending', ownerUserId: owner.me.id });

    // Confirming the real amount of a variable expense clears the estimate and re-splits it.
    const confirmed = await owner.ok('POST', `/expenses/${byName.Luz.id}/pay`, { amount: '3480.50' });
    expect(confirmed).toMatchObject({ amount: '3480.50', isEstimated: false });

    const templates = await owner.ok<any[]>('GET', '/recurring-expenses');
    expect(templates.find((t) => t.name === 'Alquiler').nextDate).toBe('2099-02-05');
  });

  it('converts an existing expense into a fixed one without duplicating it', async () => {
    const me = await registerUser(ctx, 'Ana');
    const expense = await me.ok('POST', '/expenses', {
      description: 'Internet',
      amount: '2500',
      currency: 'DOP',
      date: '2099-02-10',
      scope: 'personal',
    });
    await me.ok('POST', '/recurring-expenses', {
      name: 'Internet',
      amount: '2500',
      currency: 'DOP',
      scope: 'personal',
      dueDay: 10,
      startDate: '2099-02-10',
      linkExpenseId: expense.id,
    });
    await runJobs(ctx, me.me.household.id, '2099-03-31');
    const rows = await me.ok<any[]>('GET', '/expenses?from=2099-02-01&to=2099-03-31');
    expect(rows.map((r) => r.date).sort()).toEqual(['2099-02-10', '2099-03-10']);
    expect(rows.every((r) => r.nature === 'fixed' && r.recurringExpenseId)).toBe(true);
  });
});
