import {
  computeNet,
  occurrencesBetween,
  type IncomeKind,
  type IncomeSourceType,
  type RecurrenceRule,
  type SplitInput,
} from '@mypersonalfinance/shared';
import { eq } from 'drizzle-orm';
import type { DbOrTx, Tx } from '../../db/client';
import { incomeDeductions, incomeEntries, incomeSources, incomeSplits, sourceDeductionTemplates } from '../../db/schema';
import { resolveSplits } from '../../lib/access';
import { addDays } from '../../lib/dates';

type IncomeSource = typeof incomeSources.$inferSelect;

/** Kind of the payments a source generates automatically. */
const SCHEDULED_KIND: Record<IncomeSourceType, IncomeKind> = {
  formal_employment: 'salary',
  informal_employment: 'salary',
  freelance: 'freelance',
  investment: 'investment_return',
  savings_interest: 'interest',
  rental: 'other',
  other: 'other',
};

/** Replaces the deductions and member splits of an income entry. */
export const writeEntryChildren = async (
  db: DbOrTx,
  entryId: string,
  deductions: { deductionTypeId: string; amount: string }[],
  splits: SplitInput[],
) => {
  await db.delete(incomeDeductions).where(eq(incomeDeductions.incomeEntryId, entryId));
  await db.delete(incomeSplits).where(eq(incomeSplits.incomeEntryId, entryId));
  if (deductions.length) {
    await db.insert(incomeDeductions).values(deductions.map((d) => ({ incomeEntryId: entryId, ...d })));
  }
  if (splits.length) {
    await db
      .insert(incomeSplits)
      .values(splits.map((s) => ({ incomeEntryId: entryId, userId: s.userId, sharePct: String(s.sharePct) })));
  }
};

/** Pay schedule of a source, or null when it has none (irregular or incomplete). */
export const sourceSchedule = (source: IncomeSource): RecurrenceRule | null => {
  const frequency = source.payFrequency;
  if (frequency === 'irregular' || !source.scheduleStartDate) return null;
  const needsDay = frequency !== 'weekly' && frequency !== 'biweekly';
  if (needsDay && !source.payDay) return null;
  return {
    frequency,
    day: source.payDay ?? 1,
    secondDay: source.secondPayDay,
    startDate: source.scheduleStartDate,
    weekendRule: source.weekendRule,
  };
};

/**
 * Registers the scheduled payments of a source due up to `today` that weren't processed yet,
 * using the expected gross amount and the source's deduction template. Idempotent.
 */
export const generateScheduledIncome = async (tx: Tx, source: IncomeSource, today: string) => {
  const rule = sourceSchedule(source);
  if (!rule || !source.autoRegister || !source.isActive || !source.expectedGross || !source.accountId) return 0;
  const from = source.generatedThrough ? addDays(source.generatedThrough, 1) : rule.startDate;
  const dates = occurrencesBetween(rule, from, today);
  let created = 0;
  if (dates.length) {
    const templates = await tx
      .select()
      .from(sourceDeductionTemplates)
      .where(eq(sourceDeductionTemplates.sourceId, source.id))
      .orderBy(sourceDeductionTemplates.sortOrder);
    const deductions = templates.map((t) => ({ deductionTypeId: t.deductionTypeId, amount: t.defaultAmount }));
    const netAmount = computeNet(source.expectedGross, deductions.map((d) => d.amount));
    const splits = source.scope === 'shared' ? await resolveSplits(tx, source.householdId, undefined) : [];
    for (const date of dates) {
      const [entry] = await tx
        .insert(incomeEntries)
        .values({
          householdId: source.householdId,
          sourceId: source.id,
          kind: SCHEDULED_KIND[source.type],
          payDate: date,
          scheduledDate: date,
          grossAmount: source.expectedGross,
          netAmount,
          currency: source.defaultCurrency,
          accountId: source.accountId,
          autoGenerated: true,
          isEstimated: true,
        })
        .onConflictDoNothing()
        .returning({ id: incomeEntries.id });
      if (!entry) continue;
      await writeEntryChildren(tx, entry.id, deductions, splits);
      created++;
    }
  }
  if (source.generatedThrough !== today) {
    await tx.update(incomeSources).set({ generatedThrough: today }).where(eq(incomeSources.id, source.id));
  }
  return created;
};
