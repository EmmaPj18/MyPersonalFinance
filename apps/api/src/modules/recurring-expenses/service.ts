import { occurrencesBetween, type RecurrenceRule } from '@mypersonalfinance/shared';
import { eq } from 'drizzle-orm';
import type { DbOrTx, Tx } from '../../db/client';
import { expenses, recurringExpenses, recurringExpenseSplits } from '../../db/schema';
import { resolveSplits } from '../../lib/access';
import { addDays } from '../../lib/dates';
import { syncDebtPayment } from '../debts/service';
import { writeSplits } from '../expenses/service';

type RecurringExpense = typeof recurringExpenses.$inferSelect;

export const templateSchedule = (t: RecurringExpense): RecurrenceRule => ({
  frequency: t.frequency,
  day: t.dueDay,
  secondDay: t.secondDueDay,
  startDate: t.startDate,
  endDate: t.endDate,
  weekendRule: t.weekendRule,
});

const templateSplits = async (db: DbOrTx, t: RecurringExpense) => {
  const own = await db.select().from(recurringExpenseSplits).where(eq(recurringExpenseSplits.recurringExpenseId, t.id));
  return resolveSplits(
    db,
    t.householdId,
    own.length ? own.map((s) => ({ userId: s.userId, sharePct: Number(s.sharePct) })) : undefined,
  );
};

/**
 * Registers the occurrences of a fixed expense due up to `today` that weren't processed yet:
 * paid (autoPay) or pending otherwise. Variable-amount ones are flagged as estimated. Idempotent.
 */
export const generateScheduledExpenses = async (tx: Tx, t: RecurringExpense, today: string) => {
  if (!t.active) return 0;
  const rule = templateSchedule(t);
  const from = t.generatedThrough ? addDays(t.generatedThrough, 1) : rule.startDate;
  const dates = occurrencesBetween(rule, from, today);
  let created = 0;
  const splits = t.scope === 'shared' && dates.length ? await templateSplits(tx, t) : [];
  for (const date of dates) {
    const [expense] = await tx
      .insert(expenses)
      .values({
        householdId: t.householdId,
        categoryId: t.categoryId,
        accountId: t.accountId,
        paidByUserId: t.autoPay ? (t.paidByUserId ?? t.ownerUserId) : null,
        amount: t.amount,
        currency: t.currency,
        date,
        description: t.name,
        nature: 'fixed',
        scope: t.scope,
        ownerUserId: t.ownerUserId,
        recurringExpenseId: t.id,
        status: t.autoPay ? 'paid' : 'pending',
        autoGenerated: true,
        isEstimated: t.isVariableAmount,
        createdBy: t.paidByUserId ?? t.ownerUserId,
      })
      .onConflictDoNothing()
      .returning();
    if (!expense) continue;
    if (splits.length) await writeSplits(tx, expense.id, expense.amount, splits);
    // A loan installment also pays the linked debt.
    if (t.debtId) await syncDebtPayment(tx, t.debtId, expense);
    created++;
  }
  if (t.generatedThrough !== today) {
    await tx.update(recurringExpenses).set({ generatedThrough: today }).where(eq(recurringExpenses.id, t.id));
  }
  return created;
};

/** Future occurrences (projections, not stored) between tomorrow and `until`. */
export const upcomingDates = (rule: RecurrenceRule, generatedThrough: string | null, today: string, until: string) => {
  const from = addDays(generatedThrough && generatedThrough > today ? generatedThrough : today, 1);
  return occurrencesBetween(rule, from, until);
};
